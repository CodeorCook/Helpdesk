-- HELPDESK / PostgreSQL 12+
-- Bản thiết kế làm mới từ CSDL_Helpdesk.sql, dành cho cơ sở dữ liệu chưa có dữ liệu thật.
-- Không phải migration; KHÔNG xóa schema/tables cũ. Lệnh chạy: psql -d <database> -f CSDL_Helpdesk_Da_Chinh_Sua.sql
-- Schema riêng: helpdesk. Thời điểm lưu TIMESTAMPTZ theo timezone kết nối, quy ước UTC ở backend.
BEGIN;
CREATE SCHEMA IF NOT EXISTS helpdesk;
SET search_path TO helpdesk, public;

CREATE TABLE nguoi_dung (
  nd_ma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ho_ten VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL,
  mat_khau_hash VARCHAR(255) NOT NULL,
  so_dien_thoai VARCHAR(20),
  gioi_tinh VARCHAR(20),
  vai_tro VARCHAR(20) NOT NULL CHECK (vai_tro IN ('KHACH_HANG','NHAN_VIEN','QUAN_TRI_VIEN')),
  trang_thai VARCHAR(20) NOT NULL DEFAULT 'HOAT_DONG' CHECK (trang_thai IN ('HOAT_DONG','KHOA')),
  ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
  ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_nguoi_dung_email_lower ON nguoi_dung (lower(email));

-- Kế thừa vai trò ở CDM được triển khai bằng bảng phụ 1-1; thông tin chung chỉ nằm tại nguoi_dung.
CREATE TABLE khach_hang (
  nd_ma BIGINT PRIMARY KEY REFERENCES nguoi_dung(nd_ma) ON DELETE RESTRICT
);
CREATE TABLE nhan_vien (
  nd_ma BIGINT PRIMARY KEY REFERENCES nguoi_dung(nd_ma) ON DELETE RESTRICT
);
CREATE TABLE quan_tri_vien (
  nd_ma BIGINT PRIMARY KEY REFERENCES nguoi_dung(nd_ma) ON DELETE RESTRICT
);

CREATE TABLE nhom_ho_tro (
  nhom_ma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ten VARCHAR(100) NOT NULL UNIQUE,
  mo_ta TEXT,
  dang_hoat_dong BOOLEAN NOT NULL DEFAULT true,
  ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Mỗi nhân viên có thể ở nhiều nhóm. Quan hệ duy nhất là bảng thành viên, không lưu nhom_ma trùng ở nhan_vien.
CREATE TABLE thanh_vien_nhom (
  nhom_ma BIGINT NOT NULL REFERENCES nhom_ho_tro(nhom_ma) ON DELETE CASCADE,
  nhan_vien_ma BIGINT NOT NULL REFERENCES nhan_vien(nd_ma) ON DELETE CASCADE,
  ngay_tham_gia TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY(nhom_ma, nhan_vien_ma)
);

CREATE TABLE loai_ho_tro (
  ht_ma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ten VARCHAR(100) NOT NULL UNIQUE,
  mo_ta TEXT,
  dang_hoat_dong BOOLEAN NOT NULL DEFAULT true
);
CREATE TABLE muc_do_uu_tien (
  mdut_ma SMALLINT PRIMARY KEY,
  ten VARCHAR(40) NOT NULL UNIQUE,
  thu_tu SMALLINT NOT NULL UNIQUE CHECK (thu_tu > 0)
);
CREATE TABLE trang_thai (
  tt_ma SMALLINT PRIMARY KEY,
  ma VARCHAR(30) NOT NULL UNIQUE,
  ten VARCHAR(80) NOT NULL,
  la_ket_thuc BOOLEAN NOT NULL DEFAULT false
);

CREATE TABLE chinh_sach_sla (
  sla_ma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mdut_ma SMALLINT NOT NULL REFERENCES muc_do_uu_tien(mdut_ma) ON DELETE RESTRICT,
  ten VARCHAR(100) NOT NULL,
  thoi_gian_phan_hoi_phut INTEGER NOT NULL CHECK (thoi_gian_phan_hoi_phut > 0),
  thoi_gian_xu_ly_phut INTEGER NOT NULL CHECK (thoi_gian_xu_ly_phut > 0),
  dang_hoat_dong BOOLEAN NOT NULL DEFAULT true,
  ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (thoi_gian_xu_ly_phut >= thoi_gian_phan_hoi_phut)
);
CREATE UNIQUE INDEX uq_sla_muc_uu_tien_dang_dung ON chinh_sach_sla(mdut_ma) WHERE dang_hoat_dong = true;

CREATE TABLE phieu_ho_tro (
  phieu_ma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  khach_hang_ma BIGINT NOT NULL REFERENCES khach_hang(nd_ma) ON DELETE RESTRICT,
  -- Nếu nhân viên lập phiếu thì lưu ID nhân viên; khách tự tạo thì NULL.
  nguoi_lap_ma BIGINT REFERENCES nguoi_dung(nd_ma) ON DELETE RESTRICT,
  nguon_tao VARCHAR(20) NOT NULL DEFAULT 'KHACH_HANG' CHECK (nguon_tao IN ('KHACH_HANG','NHAN_VIEN','CHATBOT')),
  nhom_ma BIGINT REFERENCES nhom_ho_tro(nhom_ma) ON DELETE SET NULL,
  nhan_vien_phu_trach_ma BIGINT REFERENCES nhan_vien(nd_ma) ON DELETE SET NULL,
  mdut_ma SMALLINT NOT NULL REFERENCES muc_do_uu_tien(mdut_ma) ON DELETE RESTRICT,
  ht_ma BIGINT REFERENCES loai_ho_tro(ht_ma) ON DELETE SET NULL,
  tt_ma SMALLINT NOT NULL REFERENCES trang_thai(tt_ma) ON DELETE RESTRICT,
  sla_ma BIGINT REFERENCES chinh_sach_sla(sla_ma) ON DELETE SET NULL,
  tieu_de VARCHAR(200) NOT NULL CHECK (length(btrim(tieu_de)) > 0),
  mo_ta TEXT NOT NULL CHECK (length(btrim(mo_ta)) > 0),
  ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now(),
  ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT now(),
  ngay_phan_hoi_dau TIMESTAMPTZ,
  ngay_giai_quyet TIMESTAMPTZ,
  ngay_dong TIMESTAMPTZ,
  han_phan_hoi TIMESTAMPTZ,
  han_xu_ly TIMESTAMPTZ,
  ly_do_dong TEXT,
  CHECK (ngay_dong IS NULL OR ngay_dong >= ngay_tao),
  CHECK (nguon_tao <> 'NHAN_VIEN' OR nguoi_lap_ma IS NOT NULL)
);
CREATE INDEX ix_phieu_khach ON phieu_ho_tro(khach_hang_ma);
CREATE INDEX ix_phieu_nv_trangthai ON phieu_ho_tro(nhan_vien_phu_trach_ma, tt_ma);
CREATE INDEX ix_phieu_nhom ON phieu_ho_tro(nhom_ma);
CREATE INDEX ix_phieu_ngaytao ON phieu_ho_tro(ngay_tao DESC);
CREATE INDEX ix_phieu_han ON phieu_ho_tro(han_xu_ly) WHERE ngay_dong IS NULL;

CREATE TABLE lich_su_phan_cong (
  pc_ma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phieu_ma BIGINT NOT NULL REFERENCES phieu_ho_tro(phieu_ma) ON DELETE CASCADE,
  nhan_vien_ma BIGINT NOT NULL REFERENCES nhan_vien(nd_ma) ON DELETE RESTRICT,
  nguoi_phan_cong_ma BIGINT REFERENCES nguoi_dung(nd_ma) ON DELETE SET NULL,
  bat_dau TIMESTAMPTZ NOT NULL DEFAULT now(),
  ket_thuc TIMESTAMPTZ,
  ghi_chu TEXT,
  CHECK (ket_thuc IS NULL OR ket_thuc >= bat_dau)
);
CREATE UNIQUE INDEX uq_phan_cong_dang_hieu_luc ON lich_su_phan_cong(phieu_ma) WHERE ket_thuc IS NULL;
CREATE INDEX ix_pc_nv ON lich_su_phan_cong(nhan_vien_ma);

CREATE TABLE lich_su_trang_thai (
  ls_ma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phieu_ma BIGINT NOT NULL REFERENCES phieu_ho_tro(phieu_ma) ON DELETE CASCADE,
  tt_cu_ma SMALLINT REFERENCES trang_thai(tt_ma) ON DELETE RESTRICT,
  tt_moi_ma SMALLINT NOT NULL REFERENCES trang_thai(tt_ma) ON DELETE RESTRICT,
  nguoi_thay_doi_ma BIGINT REFERENCES nguoi_dung(nd_ma) ON DELETE SET NULL,
  nguon_thay_doi VARCHAR(20) NOT NULL DEFAULT 'NGUOI_DUNG' CHECK (nguon_thay_doi IN ('NGUOI_DUNG','HE_THONG')),
  thoi_diem TIMESTAMPTZ NOT NULL DEFAULT now(),
  ghi_chu TEXT,
  CHECK (tt_cu_ma IS NULL OR tt_cu_ma <> tt_moi_ma)
);
CREATE INDEX ix_ls_phieu_time ON lich_su_trang_thai(phieu_ma, thoi_diem DESC);

CREATE TABLE tep_dinh_kem (
  tep_ma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phieu_ma BIGINT NOT NULL REFERENCES phieu_ho_tro(phieu_ma) ON DELETE CASCADE,
  nguoi_tai_len_ma BIGINT REFERENCES nguoi_dung(nd_ma) ON DELETE SET NULL,
  ten VARCHAR(255) NOT NULL,
  duong_dan TEXT NOT NULL,
  mime_type VARCHAR(120),
  kich_thuoc_byte BIGINT CHECK (kich_thuoc_byte IS NULL OR kich_thuoc_byte >= 0),
  ngay_tai_len TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_tep_phieu ON tep_dinh_kem(phieu_ma);

CREATE TABLE tin_nhan (
  tn_ma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phieu_ma BIGINT NOT NULL REFERENCES phieu_ho_tro(phieu_ma) ON DELETE CASCADE,
  nguoi_gui_ma BIGINT NOT NULL REFERENCES nguoi_dung(nd_ma) ON DELETE RESTRICT,
  la_ghi_chu_noi_bo BOOLEAN NOT NULL DEFAULT false,
  noi_dung TEXT NOT NULL CHECK (length(btrim(noi_dung)) > 0),
  thoi_gian TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_tin_nhan_phieu ON tin_nhan(phieu_ma, thoi_gian);

CREATE TABLE danh_gia (
  dg_ma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phieu_ma BIGINT NOT NULL UNIQUE REFERENCES phieu_ho_tro(phieu_ma) ON DELETE CASCADE,
  khach_hang_ma BIGINT NOT NULL REFERENCES khach_hang(nd_ma) ON DELETE RESTRICT,
  so_sao SMALLINT NOT NULL CHECK (so_sao BETWEEN 1 AND 5),
  nhan_xet TEXT,
  ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE cau_hoi_mau (
  ch_ma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  noi_dung VARCHAR(255) NOT NULL,
  tu_khoa VARCHAR(255),
  cau_tra_loi TEXT NOT NULL,
  dang_hoat_dong BOOLEAN NOT NULL DEFAULT true,
  ngay_tao TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE phien_chat (
  phien_chat_ma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  khach_hang_ma BIGINT REFERENCES khach_hang(nd_ma) ON DELETE SET NULL,
  phieu_ma BIGINT UNIQUE REFERENCES phieu_ho_tro(phieu_ma) ON DELETE SET NULL,
  bat_dau TIMESTAMPTZ NOT NULL DEFAULT now(),
  ket_thuc TIMESTAMPTZ,
  CHECK (ket_thuc IS NULL OR ket_thuc >= bat_dau)
);
CREATE TABLE tin_nhan_chatbot (
  tncb_ma BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phien_chat_ma BIGINT NOT NULL REFERENCES phien_chat(phien_chat_ma) ON DELETE CASCADE,
  ch_ma BIGINT REFERENCES cau_hoi_mau(ch_ma) ON DELETE SET NULL,
  nguoi_gui VARCHAR(10) NOT NULL CHECK (nguoi_gui IN ('KHACH','BOT')),
  noi_dung TEXT NOT NULL CHECK (length(btrim(noi_dung)) > 0),
  thoi_gian TIMESTAMPTZ NOT NULL DEFAULT now(),
  da_tra_loi_duoc BOOLEAN
);
CREATE INDEX ix_tncb_phien ON tin_nhan_chatbot(phien_chat_ma, thoi_gian);

-- Quy tắc nhóm xử lý mặc định của từng loại yêu cầu (được cấu hình bởi admin).
CREATE TABLE xu_ly_mac_dinh (
  ht_ma BIGINT PRIMARY KEY REFERENCES loai_ho_tro(ht_ma) ON DELETE CASCADE,
  nhom_ma BIGINT NOT NULL REFERENCES nhom_ho_tro(nhom_ma) ON DELETE RESTRICT
);

-- Đồng bộ ngay_cap_nhat của phiếu (thay đổi khác thực hiện tại tầng service).
CREATE FUNCTION set_phieu_updated_at() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN NEW.ngay_cap_nhat := now(); RETURN NEW; END $$;
CREATE TRIGGER trg_phieu_updated_at BEFORE UPDATE ON phieu_ho_tro
FOR EACH ROW EXECUTE FUNCTION set_phieu_updated_at();


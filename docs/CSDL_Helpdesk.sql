COMMIT;

-- QUY TẮC NGHIỆP VỤ CẦN TRIỂN KHAI TRONG BACKEND (không được FK đơn lẻ bảo đảm):
-- 1. vai_tro trong nguoi_dung phải khớp bảng khach_hang/nhan_vien/quan_tri_vien.
-- 2. nguoi_lap_ma của phiếu phải hợp lệ theo nguon_tao; tin_nhan nội bộ chỉ nhân viên/admin tạo và xem.
-- 3. danh_gia.khach_hang_ma phải chính là chủ phiếu và chỉ đánh giá sau hoàn tất.
-- 4. Khi chuyển nhân viên: trong một transaction khóa phiếu (SELECT FOR UPDATE),
--    kết thúc lịch phân công cũ, tạo lịch sử mới và cập nhật nhan_vien_phu_trach_ma.
-- 5. Khi đổi trạng thái: trong một transaction cập nhật tt_ma và ghi lich_su_trang_thai.
-- 6. Khi tạo phiếu: chọn SLA đang hoạt động theo ưu tiên, lưu sla_ma và tính hạn trên chính sách
--    giờ làm việc nếu có; thiết lập ngay_phan_hoi_dau khi nhân viên phản hồi đầu tiên.
-- 7. Cảnh báo sắp/quá hạn SLA cần tác vụ nền; hiện không có scheduler tích hợp trong SQL.
-- 8. Kiểm tra tệp đính kèm: MIME, kích thước, đường dẫn an toàn, phân quyền tải trên backend.
-- 9. Password chỉ được lưu dưới dạng hash mạnh (Argon2id/bcrypt), không lưu mật khẩu rõ.
-- 10. 'DA_HUY' giữ làm trạng thái dữ liệu để tương thích nghiệp vụ, không có nghĩa phải
--     tạo use case 'Hủy phiếu' cho nhân viên trong sơ đồ final.

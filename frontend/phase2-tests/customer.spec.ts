import { expect, test } from '@playwright/test';
const password=process.env.HELPDESK_PHASE2_PASSWORD!;
const fixtures=JSON.parse(process.env.HELPDESK_PHASE2_FIXTURES||'{}') as Record<string,{email:string;ticket_id:string}>;
if(!password)throw new Error('Chạy scripts/test_phase2.py --execute --stage E --browser để dùng fixture rollback.');

test('register → login → create → list/detail → message/file → profile → logout',async({page},testInfo)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 const email=`ui-${testInfo.project.name}-${Date.now()}@example.com`;
 await page.goto('/login',{waitUntil:'domcontentloaded'});
 await page.getByRole('link',{name:'Đăng ký',exact:true}).click();
 await expect(page).toHaveURL('/register');
 await page.getByLabel('Họ và tên',{exact:true}).fill('Khách dùng thử giao diện');
 await page.getByLabel('Email',{exact:true}).fill(email);
 await page.getByLabel('Mật khẩu',{exact:true}).fill(password);
 await page.getByLabel('Xác nhận mật khẩu',{exact:true}).fill(password);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.getByRole('button',{name:'Đăng ký',exact:true}).click();
 await expect(page).toHaveURL('/login');
 await expect(page.getByRole('status')).toContainText('Đăng ký thành công');
 await page.getByLabel('Email',{exact:true}).fill(email);
 await page.getByLabel('Mật khẩu',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();
 await expect(page).toHaveURL('/customer');
 await expect(page.getByRole('heading',{name:'Thông tin tài khoản',exact:true})).toBeVisible();
 await page.getByRole('link',{name:'Tạo phiếu hỗ trợ',exact:true}).first().click();
 await page.getByLabel('Tiêu đề',{exact:true}).fill('Yêu cầu từ trình duyệt');
 await expect(page.getByRole('combobox',{name:'Loại hỗ trợ'}).locator('option')).not.toHaveCount(1);
 await page.getByRole('combobox',{name:'Loại hỗ trợ'}).selectOption({index:1});
 await page.getByLabel('Mô tả chi tiết').fill('Cần hướng dẫn sử dụng dịch vụ.');
 await page.getByLabel('Tệp đính kèm (không bắt buộc)').setInputFiles({name:'browser.txt',mimeType:'text/plain',buffer:Buffer.from('Tep browser UTF8')});
 await page.getByRole('button',{name:'Gửi yêu cầu hỗ trợ',exact:true}).click();
 await expect(page).toHaveURL(/\/customer\/tickets\/\d+$/);
 await expect(page.getByRole('heading',{name:'Yêu cầu từ trình duyệt',exact:true})).toBeVisible();
 await expect(page.getByText('browser.txt',{exact:true})).toBeVisible();
 await page.reload({waitUntil:'domcontentloaded'}); // token CSRF reloaded, not only remembered after login
 await page.getByLabel('Nội dung phản hồi').fill('Bổ sung thông tin từ khách hàng.');
 await page.getByRole('button',{name:'Gửi phản hồi',exact:true}).click();
 await expect(page.getByText('Bổ sung thông tin từ khách hàng.',{exact:true})).toBeVisible();
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Tải xuống browser.txt',exact:true}).click();
 expect((await downloadPromise).suggestedFilename()).toBe('browser.txt');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.screenshot({path:`test-results/customer-detail-${testInfo.project.name}.png`,fullPage:true});
 await page.getByRole('navigation',{name:'Không gian Khách hàng'}).getByRole('link',{name:'Phiếu của tôi',exact:true}).click();
 await page.getByLabel('Tiêu đề phiếu').fill('Yêu cầu từ trình duyệt');
 await page.getByRole('button',{name:'Áp dụng',exact:true}).click();
 await expect(page.getByRole('link',{name:'Yêu cầu từ trình duyệt',exact:true})).toBeVisible();
 await page.getByRole('navigation',{name:'Không gian Khách hàng'}).getByRole('link',{name:'Thông tin cá nhân',exact:true}).click();
 await page.getByLabel('Họ và tên',{exact:true}).fill('Khách đã cập nhật');
 await page.getByRole('button',{name:'Lưu thay đổi',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Đã cập nhật hồ sơ');
 // A file failure must not lose or duplicate the ticket that was already saved.
 await page.getByRole('navigation',{name:'Không gian Khách hàng'}).getByRole('link',{name:'Tạo phiếu hỗ trợ',exact:true}).click();
 await page.getByLabel('Tiêu đề',{exact:true}).fill('Phiếu được lưu dù tệp lỗi');
 await expect(page.getByRole('combobox',{name:'Loại hỗ trợ'}).locator('option')).not.toHaveCount(1);
 await page.getByRole('combobox',{name:'Loại hỗ trợ'}).selectOption({index:1});
 await page.getByLabel('Mô tả chi tiết').fill('Tệp giả phải bị từ chối mà không gửi lại phiếu.');
 await page.getByLabel('Tệp đính kèm (không bắt buộc)').setInputFiles({name:'fake.png',mimeType:'image/png',buffer:Buffer.from('not a PNG')});
 await page.getByRole('button',{name:'Gửi yêu cầu hỗ trợ',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Phiếu được lưu dù tệp lỗi',exact:true})).toBeVisible();
 await expect(page.getByRole('alert')).toContainText('Phiếu đã được tạo, nhưng tệp chưa tải lên');
 expect((await page.request.get('/api/v1/customer/tickets')).ok()).toBeTruthy();
 expect((await (await page.request.get('/api/v1/customer/tickets')).json()).total).toBe(2);
 await page.goto('/manager',{waitUntil:'domcontentloaded'});
 await expect(page.getByRole('heading',{name:'Không đủ quyền truy cập'})).toBeVisible();
 await page.getByRole('link',{name:'Đến không gian của bạn'}).click();
 await expect(page.getByRole('heading',{name:'Thông tin tài khoản',exact:true})).toBeVisible();
 await page.screenshot({path:`test-results/customer-overview-${testInfo.project.name}.png`,fullPage:true});
 await page.getByRole('button',{name:'Đăng xuất',exact:true}).click();
 await expect(page).toHaveURL('/login');expect(errors).toEqual([]);
});

test('resolved fixture → confirm close → one-time rating',async({page},testInfo)=>{
 const fixture=fixtures[testInfo.project.name];
 await page.goto('/login',{waitUntil:'domcontentloaded'});
 await page.getByLabel('Email',{exact:true}).fill(fixture.email);
 await page.getByLabel('Mật khẩu',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();
 await expect(page).toHaveURL('/customer');
 await page.goto(`/customer/tickets/${fixture.ticket_id}`,{waitUntil:'domcontentloaded'});
 await page.getByRole('button',{name:'Đóng phiếu',exact:true}).click();
 await page.getByRole('button',{name:'Xác nhận đóng',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Đánh giá hỗ trợ',exact:true})).toBeVisible();
 await page.getByRole('radio',{name:'5 ★',exact:true}).check();
 await page.getByLabel('Nhận xét (không bắt buộc)').fill('Đã được hỗ trợ đầy đủ.');
 await page.getByRole('button',{name:'Gửi đánh giá',exact:true}).click();
 await expect(page.getByText('5/5 sao',{exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Gửi đánh giá',exact:true})).toHaveCount(0);
});
